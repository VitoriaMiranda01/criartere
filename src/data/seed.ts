// Helper para calcular datas relativas a hoje
// Garantimos que os pedidos cobrem os últimos ~6 meses e o mês atual
function calcDate(daysAgo: number): string {
  const d = new Date()
  d.setDate(d.getDate() - daysAgo)
  return d.toISOString().slice(0, 10)
}

